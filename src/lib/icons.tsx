/** Renders "@icon-name text" tokens (icon followed by text) or plain text. */
export function Lbl({ text, className }: { text: string; className?: string }) {
  const m = /^@([a-z0-9-]+) ([\s\S]*)$/.exec(text);
  if (!m) return <>{text}</>;
  const Icon = iconByName(m[1]);
  return (
    <>
      <Icon className={className ?? "mr-1.5 inline size-3.5 -translate-y-px"} />
      {m[2]}
    </>
  );
}
